"""One-off helper: vendor Google Fonts (Plus Jakarta Sans) as local woff2 files.

Usage:  .\.venv\Scripts\python.exe scripts\vendor_fonts.py

Produces:
  app/static/vendor/fonts/*.woff2
  app/static/vendor/fonts.css

Run once and commit the result. Keeps the UI fully usable offline (audit F-24).
"""
from __future__ import annotations

import re
import urllib.request
from pathlib import Path

FAMILY = "Plus Jakarta Sans"
WEIGHTS = [400, 500, 600, 700, 800]
CSS_URL = (
    "https://fonts.googleapis.com/css2?"
    "family=Plus+Jakarta+Sans:wght@400;500;600;700;800&display=swap"
)
UE = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36"
)

ROOT = Path(__file__).resolve().parent.parent
FONT_DIR = ROOT / "app" / "static" / "vendor" / "fonts"
CSS_OUT = ROOT / "app" / "static" / "vendor" / "fonts.css"


def fetch(url: str) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": UE})
    with urllib.request.urlopen(request, timeout=30) as response:
        return response.read()


def main() -> None:
    FONT_DIR.mkdir(parents=True, exist_ok=True)
    css = fetch(CSS_URL).decode("utf-8")

    # Only keep the latin subset blocks (skip latin-ext/cyrillic/etc).
    blocks = re.findall(r"/\*\s*([\w-]+)\s*\*/\s*(@font-face\s*\{[^}]+\})", css)
    rules: list[str] = []
    downloaded = 0

    for subset, block in blocks:
        if subset != "latin":
            continue
        weight_match = re.search(r"font-weight:\s*(\d+)", block)
        if not weight_match:
            continue
        weight = int(weight_match.group(1))
        if weight not in WEIGHTS:
            continue
        url_match = re.search(r"url\((https://[^)]+\.woff2)\)", block)
        if not url_match:
            continue

        filename = f"plus-jakarta-sans-{weight}.woff2"
        target = FONT_DIR / filename
        if not target.exists():
            target.write_bytes(fetch(url_match.group(1)))
            downloaded += 1

        rules.append(
            "@font-face {\n"
            f"  font-family: '{FAMILY}';\n"
            "  font-style: normal;\n"
            f"  font-weight: {weight};\n"
            "  font-display: swap;\n"
            "  src: url('/static/vendor/fonts/"
            f"{filename}') format('woff2');\n"
            "  unicode-range: U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, "
            "U+02C6, U+02DA, U+02DC, U+2000-206F, U+2074, U+20AC, U+2122, "
            "U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD;\n"
            "}"
        )

    if not rules:
        raise SystemExit("No latin @font-face rules found; Google Fonts format changed.")

    header = (
        "/* Vendored Plus Jakarta Sans (latin subset, woff2).\n"
        "   Generated by scripts/vendor_fonts.py — do not edit by hand.\n"
        "   Local copy removes the external CDN dependency (audit finding F-24). */\n"
    )
    CSS_OUT.write_text(header + "\n\n".join(rules) + "\n", encoding="utf-8")
    print(f"Downloaded {downloaded} font files; wrote {CSS_OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
